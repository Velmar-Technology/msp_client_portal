const fs = require('fs');
const path = require('path');

/**
 * Recursively collects contract module export paths under a directory.
 * Supports both flat (`src/<domain>/<domain>.contract.ts`) and hierarchical
 * (`src/<parent>/<child>/<child>.contract.ts`) directory trees.
 *
 * @param dir - Directory to scan
 * @param relPrefix - Relative path prefix from `src/`
 * @returns Array of relative module specifiers
 */
function collectContractModules(dir, relPrefix = '') {
  const entries = fs
    .readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name));

  const results = [];
  const tsFiles = entries.filter(
    (e) =>
      e.isFile() &&
      e.name.endsWith('.ts') &&
      !e.name.endsWith('.d.ts') &&
      !e.name.endsWith('.test.ts') &&
      !e.name.endsWith('.spec.ts') &&
      !e.name.endsWith('.generated.ts')
  );

  if (relPrefix) {
    if (tsFiles.some((f) => f.name === 'index.ts')) {
      results.push(`./${relPrefix}`);
    } else {
      for (const file of tsFiles) {
        const baseName = file.name.replace(/\.ts$/, '');
        results.push(`./${relPrefix}/${baseName}`);
      }
    }
  }

  for (const entry of entries) {
    if (entry.isDirectory()) {
      const childPrefix = relPrefix ? `${relPrefix}/${entry.name}` : entry.name;
      results.push(...collectContractModules(path.join(dir, entry.name), childPrefix));
    }
  }

  return results;
}

/**
 * Automatically scans `packages/contracts/src/` and generates
 * `src/contracts.generated.ts` so adding flat or hierarchical contracts requires
 * zero manual edits to `packages/contracts/src/index.ts`.
 */
function syncContractsBarrel() {
  const srcDir = path.join(__dirname, '../src');
  const outFile = path.join(srcDir, 'contracts.generated.ts');

  const specs = collectContractModules(srcDir);
  const exportsList = specs.map((spec) => `export * from '${spec}';`);

  const content = [
    '// AUTO-GENERATED FILE — DO NOT EDIT MANUALLY.',
    '// Generated by packages/contracts/scripts/sync-barrel.js',
    ...exportsList,
    '',
  ].join('\n');

  const existing = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : null;
  if (existing !== content) {
    fs.writeFileSync(outFile, content, 'utf8');
  }
}

syncContractsBarrel();
module.exports = { syncContractsBarrel };
